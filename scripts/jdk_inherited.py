"""Writes crates/lower/src/symbols/jdk_inherited.rs: the public instance methods javalib's JDK
classes declare that the JDK's classes inherit from a superclass (`scripts/JdkInherited.java`, by
name), as `java` of JDK 21 on the path loads them, from the NIR of ref/libs's javalib."""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JAVALIB = ROOT / "ref/libs/javalib_native0.5_3-0.5.12.jar"
OUT = ROOT / "crates/lower/src/symbols/jdk_inherited.rs"
DUMP = ROOT / "target/release/scivolo-nir-dump"
METHODS = ROOT / "tmp/jdk-inherited/methods.tsv"
JDK = "21"
DEF = re.compile(r"^(?:[a-z]+ )*def @((?:java|javax)\.[\w.]+)::(\w+)\(")


def main():
    version = subprocess.run(["java", "-version"], capture_output=True, text=True).stderr
    if f'version "{JDK}' not in version:
        sys.exit(f"java of JDK {JDK} expected, found {version.splitlines()[0]}")
    nir = subprocess.run([str(DUMP), "--dump", str(JAVALIB)], capture_output=True, text=True, check=True).stdout
    methods = sorted({m.groups() for line in nir.splitlines() if (m := DEF.match(line))})
    METHODS.parent.mkdir(parents=True, exist_ok=True)
    METHODS.write_text("".join(f"{c}\t{n}\n" for c, n in methods))
    out = subprocess.run(["java", str(ROOT / "scripts/JdkInherited.java"), str(METHODS)],
                         capture_output=True, text=True, check=True).stdout
    rows = sorted(tuple(line.split("\t")) for line in out.splitlines())
    lines = [f'    ("{c}", "{n}", "{s}"),' for c, s, n in rows]
    OUT.write_text(f"""\
// Generated by `python3 scripts/jdk_inherited.py` from JDK {JDK}.
//! The public instance methods javalib's classes declare that the JDK's classes of the same name
//! inherit: each class, method name and the JDK superclass declaring it, sorted.

pub const INHERITED: [(&str, &str, &str); {len(rows)}] = [
{chr(10).join(lines)}
];
""")
    print(f"{len(rows)} methods in {OUT.relative_to(ROOT)}")


main()
