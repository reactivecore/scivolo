#!/usr/bin/env python3
"""A module of Scala Native's library compiled file by file through the own frontend (research 36).

Usage: scripts/lib-compile.py MODULE [FILTER]

MODULE is one of MODULES or `all`. Each `.scala` file of the module's Scala 3 source directories
in ref/scala-native, scalalib's those of scalalib_sources.py (those whose paths contain FILTER),
except the classes the published scalalib takes from Scala 2.13, is lowered on its own, or with its group of
UNITS as one unit, its macros run, against the jars of tmp/lib/sn/jars (`just lib-oracle`) if
there, else the published ones, into tmp/lib/MODULE/out/FILE/; each NIR file written is compared,
as `just nir-cmp` compares them (nir_compare.py), with the oracle's: the module compiled by Scala
Native's build (Scala 3.9.0) in tmp/lib/sn/MODULE (`just lib-oracle`) if there, else the
published jar's (Scala 3.1.3), unpacked into tmp/lib/jars/MODULE.

Writes under tmp/lib/MODULE: results.tsv (file, ok|refused|timeout|crashed, reason, NIR files
same, differing, missing from the oracle, same but for var-slot order, same but for the positions
in TASTy quotes), cmp.tsv (NIR file, same|differ|var-order|quote-pos|missing, differing lines
besides var-slot order, 1 if var slots were aligned), diffs/ (the oracle's dump against ours of
each differing NIR file), refusals.txt (reasons by count, positions stripped), oracle-only.txt
on a full run (oracle NIR files not generated by any source), and prints one summary line. With FILTER, the rows of the files run
replace those of the last run. Files worse than in baseline.tsv (`just lib-baseline MODULE`) are
listed.
"""
import collections
import concurrent.futures
import os
import re
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

import scalalib_sources
from nir_compare import compare, dump

ROOT = Path(__file__).resolve().parent.parent
SN = ROOT / "ref/scala-native"
LIBS = Path(os.environ.get("SCIVOLO_LIBS", ROOT / "ref/libs"))
WORK = ROOT / "tmp/lib"
ORACLE_JARS = WORK / "sn/jars"
ENV = os.environ | {"SCIVOLO_LIBS": str(ORACLE_JARS)} if ORACLE_JARS.is_dir() else None
LOWER = ROOT / "target/release/scivolo-lower"
MODULES = ["nativelib", "clib", "posixlib", "windowslib", "javalib", "auxlib", "scalalib"]
SOURCE_DIRS = ["scala", "scala-3", "scala-2.13+"]
VERSION = "0.5.12"
WINDOWSLIB = LIBS / f"windowslib_native0.5_3-{VERSION}.jar"
JDK_STUBS = ROOT / "libs/jdk-stubs.jar"
# The options of a module's sources: the TASTy they see beyond the frontend's library
# (windowslib's, which the library lacks, and the JDK classes javalib does not define), and
# javalib's own classes as Scala classes, the JDK stubs' as Java classes.
OPTIONS = {
    "nativelib": ["--jdk-tasty", str(JDK_STUBS)],
    "windowslib": ["--tasty", str(WINDOWSLIB)],
    "javalib": ["--javalib", "--tasty", str(WINDOWSLIB), "--jdk-tasty", str(JDK_STUBS)],
    "scalalib": scalalib_sources.OPTIONS,
}
# The groups of files of a module lowered as one unit, by path prefix in their source directory:
# files that refer to each other's classes.
UNITS = {
    "auxlib": [["scala/collection/concurrent/"],
               ["scala/runtime/BoxedUnit.scala", "scala/scalanative/runtime/BoxedUnit.scala"]],
}
# The option that makes scivolo-jvm and scivolo-lower write the output of a unit's accepted files.
LEAVE_OUT = "--leave-out-refused"
JOBS = os.cpu_count() or 4
TIMEOUT = 60


def jar_name(module):
    return f"{module}_native0.5_3-{'3.9.0%2B' if module == 'scalalib' else ''}{VERSION}.jar"


SCALALIB_SOURCEROOT = WORK / "scalalib/sourceroot"
SCALALIB_LINK = SCALALIB_SOURCEROOT / "scalalib/target/scalaSources/3.9.0"


def link_scalalib_root(root):
    """Makes SCALALIB_LINK, Scala Native's `scalalib/target/scalaSources/3.9.0` under
    SCALALIB_SOURCEROOT, a link to `root`."""
    SCALALIB_LINK.parent.mkdir(parents=True, exist_ok=True)
    if SCALALIB_LINK.is_symlink() and SCALALIB_LINK.resolve() == root.resolve():
        return
    SCALALIB_LINK.unlink(missing_ok=True)
    SCALALIB_LINK.symlink_to(root.resolve())


def lower_cmd(module, root, files, out):
    """The `scivolo-lower` command lowering `files` of source directory `root` into `out`, the
    checkout the source root as in Scala Native's build (scalalib's through SCALALIB_LINK), against
    the JDK 17 API as that build but javalib's own (ADR 0095)."""
    sourceroot = SN
    if module == "scalalib":
        sourceroot = SCALALIB_SOURCEROOT
        root, files = SCALALIB_LINK, [SCALALIB_LINK / f.relative_to(root) for f in files]
    roots = ["--sourceroot", str(sourceroot), "--position-root", str(root)]
    jdk = [] if module == "javalib" else ["--jdk-17"]
    return [str(LOWER), LEAVE_OUT, "--macros", *OPTIONS.get(module, []), *jdk, *roots, *map(str, files), str(out)]


def oracle(module):
    """The NIR the module's is compared with: Scala Native's build of it from `just lib-oracle` if
    there, else the published jar's files, unpacked once."""
    if (WORK / "sn" / module).is_dir():
        return WORK / "sn" / module
    out = WORK / "jars" / module
    if not (out / ".done").exists():
        with zipfile.ZipFile(LIBS / jar_name(module)) as jar:
            jar.extractall(out)
        (out / ".done").touch()
    return out


def units(module, filter_):
    """(source directory, files) of each unit of `module`'s Scala sources with a file whose path
    contains `filter_`: each group of UNITS, each other file on its own."""
    found = {}
    roots = [scalalib_sources.sources(LIBS)] if module == "scalalib" else [SN / module / "src/main" / n for n in SOURCE_DIRS]
    for root in roots:
        for f in sorted(root.rglob("*.scala")):
            rel = str(f.relative_to(root))
            group = next((i for i, g in enumerate(UNITS.get(module, [])) if rel.startswith(tuple(g))), rel)
            found.setdefault((root, group), []).append(f)
    return [(root, fs) for (root, _), fs in found.items() if any(filter_ in str(f.relative_to(ROOT)) for f in fs)]


def run(cmd, timeout, env=None):
    """(ok|timeout|crashed|refused, reason, stdout) of frontend command `cmd`."""
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, errors="replace", timeout=timeout, env=env)
    except subprocess.TimeoutExpired:
        return "timeout", "", ""
    if r.returncode == 0:
        return "ok", "", r.stdout
    if m := re.search(r"panicked at (\S+):\n(.*)", r.stderr):
        return "crashed", f"{m[2]} at {m[1]}".replace("\t", " ")[:200], ""
    return "refused", next((l for l in r.stderr.splitlines() if l.strip()), "").replace("\t", " ")[:200], ""


def one(module, root, files, env):
    """The rows of results.tsv and of cmp.tsv of each of source files `files`, lowered as one unit
    with environment `env`; a NIR file counts for the file of its first position."""
    shown = [f"{root.name}/{f.relative_to(root)}" for f in files]
    out = WORK / module / "out" / root.name / str(files[0].relative_to(root)).removesuffix(".scala")
    state, reason, stdout = run(lower_cmd(module, root, files, out), TIMEOUT * len(files), env)
    if state != "ok":
        return [([s, state, reason, 0, 0, 0, 0, 0], []) for s in shown]
    theirs, by_file = oracle(module), {s: (collections.Counter(), []) for s in shown}
    for name in stdout.split():
        path = name.removesuffix(".nir").replace(".", "/") + ".nir"
        if module == "scalalib" and scalalib_sources.specialized(path):
            continue
        positions = (l[2:].rsplit(":", 2)[0] for l in dump(out / path) if l.startswith("@ ")) if files[1:] else iter(())
        counts, cmp = by_file.get(f"{root.name}/{next(positions, None)}", by_file[shown[0]])
        state, lines, reordered = compare(out / path, theirs / path, WORK / module / "diffs" / f"{path}.diff")
        counts[state] += 1
        cmp.append([path, state, lines, str(int(reordered))])
    keys = ("same", "differ", "missing", "var-order", "quote-pos")
    return [([s, "ok", "", *(c[k] for k in keys)], cmp) for s, (c, cmp) in by_file.items()]


def read_tsv(path):
    return [l.split("\t") for l in path.read_text().splitlines()] if path.exists() else []


def write_tsv(path, rows):
    path.write_text("".join("\t".join(map(str, r)) + "\n" for r in rows))


def worse(old, new):
    """Whether row `new` of a file is worse than its baseline row `old`."""
    rank = {"ok": 2, "refused": 1}
    return rank.get(new[1], 0) < rank.get(old[1], 0) or int(new[3]) < int(old[3])


def compile_module(module, filter_):
    work = WORK / module
    keep = filter_ != ""
    if not keep:
        shutil.rmtree(work / "diffs", ignore_errors=True)
    work.mkdir(parents=True, exist_ok=True)
    todo = units(module, filter_)
    env = ENV
    if module == "scalalib" and ENV:
        env = ENV | {"SCIVOLO_LIBS": str(scalalib_sources.libs(ORACLE_JARS))}
    if module == "scalalib":
        link_scalalib_root(scalalib_sources.sources(LIBS))
    with concurrent.futures.ThreadPoolExecutor(JOBS) as pool:
        done = [row for rows in pool.map(lambda t: one(module, *t, env), todo) for row in rows]
    rows = {r[0]: r + ["0"] * (8 - len(r)) for r in read_tsv(work / "results.tsv")} if keep else {}
    rows |= {r[0]: r for r, _ in done}
    write_tsv(work / "results.tsv", sorted(rows.values()))
    ran = {r[0] for r, _ in done}
    old_cmp = [c for c in read_tsv(work / "cmp.tsv") if c[0] not in ran] if keep else []
    compared = sorted(old_cmp + [[r[0], *c] for r, cmp in done for c in cmp])
    write_tsv(work / "cmp.tsv", compared)
    reasons = collections.Counter(f"crashed: {r[2]}" if r[1] == "crashed" else re.sub(r" at ([^ ]+:)?\d+:\d+", "", r[2])
                                  for r in rows.values() if r[1] != "ok")
    (work / "refusals.txt").write_text("".join(f"{c:5} {r}\n" for r, c in reasons.most_common()))
    states = collections.Counter(r[1] for r in rows.values())
    nir = [sum(int(r[i]) for r in rows.values()) for i in (3, 4, 5, 6, 7)]
    mixed = sum(1 for c in compared if c[2] == "differ" and c[4:] == ["1"])
    print(f"{module}: {states['ok']} ok, {states['refused']} refused, {states['timeout']} timeout, "
          f"{states['crashed']} crashed; "
          f"nir {nir[0]} same, {nir[1]} differ ({mixed} of them also var-order), {nir[3]} var-order, {nir[4]} quote-pos, "
          f"{nir[2]} missing (oracle {oracle(module).relative_to(ROOT)})")
    if not keep:
        expected = {str(p.relative_to(oracle(module))) for p in oracle(module).rglob("*.nir")
                    if module != "scalalib" or not scalalib_sources.specialized(str(p.relative_to(oracle(module))))}
        generated = {c[1] for c in compared}
        missing = sorted(expected - generated)
        (work / "oracle-only.txt").write_text("".join(f"{p}\n" for p in missing))
        print(f"  {len(missing)} oracle NIR files not generated (see {work.relative_to(ROOT)}/oracle-only.txt)")
    baseline = {r[0]: r for r in read_tsv(work / "baseline.tsv")}
    for r in sorted(rows.values()):
        if r[0] in baseline and worse(baseline[r[0]], r):
            print(f"  worse: {r[0]}: {r[1]} {r[2]} (baseline: {baseline[r[0]][1]}, {baseline[r[0]][3]} same)")


if __name__ == "__main__":
    if len(sys.argv) not in (2, 3) or sys.argv[1] not in [*MODULES, "all"]:
        sys.exit(__doc__)
    for m in MODULES if sys.argv[1] == "all" else [sys.argv[1]]:
        compile_module(m, sys.argv[2] if len(sys.argv) == 3 else "")
