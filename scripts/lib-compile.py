#!/usr/bin/env python3
"""A module of Scala Native's library compiled file by file through the own frontend (research 36).

Usage: scripts/lib-compile.py MODULE [FILTER]

MODULE is one of MODULES or `all`. Each `.scala` file of the module's Scala 3 source directories
in ref/scala-native (those whose paths contain FILTER) is lowered on its own, its macros run, against
the jars of tmp/lib/sn/jars (`just lib-oracle`) if there, else the published ones, into
tmp/lib/MODULE/out/FILE/; each NIR file written is compared, as `just
nir-cmp` compares them, with the oracle's: the module compiled by Scala Native's build (Scala
3.9.0) in tmp/lib/sn/MODULE (`just lib-oracle`) if there, else the published jar's (Scala
3.1.3), unpacked into tmp/lib/jars/MODULE.

Writes under tmp/lib/MODULE: results.tsv (file, ok|refused|timeout|crashed, reason, NIR files
same, differing, missing from the oracle), cmp.tsv (NIR file, same|differ|missing, differing
lines), diffs/ (the oracle's dump against ours of each differing NIR file), refusals.txt
(reasons by count, positions stripped), oracle-only.txt on a full run (oracle NIR files not
generated by any source), and prints one summary line. With FILTER, the rows of
the files run replace those of the last run. Files worse than in baseline.tsv (`just
lib-baseline MODULE`) are listed.
"""
import collections
import concurrent.futures
import difflib
import os
import re
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SN = ROOT / "ref/scala-native"
LIBS = Path(os.environ.get("SCIVOLO_LIBS", ROOT / "ref/libs"))
WORK = ROOT / "tmp/lib"
ORACLE_JARS = WORK / "sn/jars"
LOWER, NIR_DUMP = ROOT / "target/release/scivolo-lower", ROOT / "target/release/scivolo-nir-dump"
MODULES = ["nativelib", "clib", "posixlib", "windowslib", "javalib", "auxlib"]
SOURCE_DIRS = ["scala", "scala-3", "scala-2.13+"]
WINDOWSLIB = LIBS / "windowslib_native0.5_3-0.5.12.jar"
JDK_STUBS = ROOT / "libs/jdk-stubs.jar"
# The options of a module's sources: the TASTy they see beyond the frontend's library
# (windowslib's, which the library lacks, and the JDK classes javalib does not define), and
# javalib's own classes as Scala classes.
OPTIONS = {
    "nativelib": ["--tasty", str(JDK_STUBS)],
    "windowslib": ["--tasty", str(WINDOWSLIB)],
    "javalib": ["--javalib", "--tasty", str(WINDOWSLIB), "--tasty", str(JDK_STUBS)],
}
JOBS = os.cpu_count() or 4
TIMEOUT = 60


def sources(module, filter_):
    """(source directory, file) of each Scala source of `module` whose path contains `filter_`."""
    found = []
    for name in SOURCE_DIRS:
        root = SN / module / "src/main" / name
        found += [(root, f) for f in sorted(root.rglob("*.scala")) if filter_ in str(f.relative_to(SN))]
    return found


def oracle(module):
    """The NIR the module's is compared with: Scala Native's build of it from `just lib-oracle` if
    there, else the published jar's files, unpacked once."""
    if (WORK / "sn" / module).is_dir():
        return WORK / "sn" / module
    out = WORK / "jars" / module
    if not (out / ".done").exists():
        with zipfile.ZipFile(LIBS / f"{module}_native0.5_3-0.5.12.jar") as jar:
            jar.extractall(out)
        (out / ".done").touch()
    return out


def dump(path):
    r = subprocess.run([str(NIR_DUMP), "--debug", "--sorted", str(path)], capture_output=True, text=True,
                       errors="replace")
    if r.returncode != 0:
        return [f"nir-dump failed on {path}: {r.stderr.strip()}"]
    return [l for l in r.stdout.splitlines() if not l.startswith(("// ", "# "))]


def compare(ours, theirs, diff_file):
    """`same`, `differ N` (changed lines, the diff written to `diff_file`) or `missing`."""
    if not theirs.exists():
        return "missing", 0
    diff = list(difflib.unified_diff(dump(theirs), dump(ours), "oracle", "ours", lineterm="", n=0))
    changed = sum(1 for l in diff if l[:1] in "+-" and not l.startswith(("+++", "---")))
    if changed == 0:
        return "same", 0
    diff_file.parent.mkdir(parents=True, exist_ok=True)
    diff_file.write_text("\n".join(diff) + "\n")
    return "differ", changed


def one(module, root, file):
    """The row of results.tsv and the rows of cmp.tsv of one source file."""
    rel = str(file.relative_to(root))
    shown = f"{root.name}/{rel}"
    out = WORK / module / "out" / root.name / rel.removesuffix(".scala")
    cmd = [str(LOWER), "--macros", *OPTIONS.get(module, []), "--sourceroot", str(root), str(file), str(out)]
    env = os.environ | {"SCIVOLO_LIBS": str(ORACLE_JARS)} if ORACLE_JARS.is_dir() else None
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, errors="replace", timeout=TIMEOUT, env=env)
    except subprocess.TimeoutExpired:
        return [shown, "timeout", "", 0, 0, 0], []
    if r.returncode != 0:
        if m := re.search(r"panicked at (\S+):\n(.*)", r.stderr):
            return [shown, "crashed", f"{m[2]} at {m[1]}".replace("\t", " ")[:200], 0, 0, 0], []
        reason = next((l for l in r.stderr.splitlines() if l.strip()), "").replace("\t", " ")[:200]
        return [shown, "refused", reason, 0, 0, 0], []
    theirs, cmp, counts = oracle(module), [], collections.Counter()
    for name in r.stdout.split():
        path = name.removesuffix(".nir").replace(".", "/") + ".nir"
        state, lines = compare(out / path, theirs / path, WORK / module / "diffs" / f"{path}.diff")
        counts[state] += 1
        cmp.append([path, state, lines])
    return [shown, "ok", "", counts["same"], counts["differ"], counts["missing"]], cmp


def read_tsv(path):
    return [l.split("\t") for l in path.read_text().splitlines()] if path.exists() else []


def write_tsv(path, rows):
    path.write_text("".join("\t".join(map(str, r)) + "\n" for r in rows))


def worse(old, new):
    """Whether row `new` of a file is worse than its baseline row `old`."""
    rank = {"ok": 2, "refused": 1}
    return rank.get(new[1], 0) < rank.get(old[1], 0) or int(new[3]) < int(old[3])


def compile_module(module, filter_):
    work = WORK / module
    keep = filter_ != ""
    if not keep:
        shutil.rmtree(work / "diffs", ignore_errors=True)
    work.mkdir(parents=True, exist_ok=True)
    todo = sources(module, filter_)
    with concurrent.futures.ThreadPoolExecutor(JOBS) as pool:
        done = list(pool.map(lambda t: one(module, *t), todo))
    rows = {r[0]: r for r in read_tsv(work / "results.tsv")} if keep else {}
    rows |= {r[0]: r for r, _ in done}
    write_tsv(work / "results.tsv", sorted(rows.values()))
    ran = {r[0] for r, _ in done}
    old_cmp = [c for c in read_tsv(work / "cmp.tsv") if c[0] not in ran] if keep else []
    compared = sorted(old_cmp + [[r[0], *c] for r, cmp in done for c in cmp])
    write_tsv(work / "cmp.tsv", compared)
    reasons = collections.Counter(f"crashed: {r[2]}" if r[1] == "crashed" else re.sub(r" at ([^ ]+:)?\d+:\d+", "", r[2])
                                  for r in rows.values() if r[1] != "ok")
    (work / "refusals.txt").write_text("".join(f"{c:5} {r}\n" for r, c in reasons.most_common()))
    states = collections.Counter(r[1] for r in rows.values())
    nir = [sum(int(r[i]) for r in rows.values()) for i in (3, 4, 5)]
    print(f"{module}: {states['ok']} ok, {states['refused']} refused, {states['timeout']} timeout, "
          f"{states['crashed']} crashed; "
          f"nir {nir[0]} same, {nir[1]} differ, {nir[2]} missing (oracle {oracle(module).relative_to(ROOT)})")
    if not keep:
        expected = {str(p.relative_to(oracle(module))) for p in oracle(module).rglob("*.nir")}
        generated = {c[1] for c in compared}
        missing = sorted(expected - generated)
        (work / "oracle-only.txt").write_text("".join(f"{p}\n" for p in missing))
        print(f"  {len(missing)} oracle NIR files not generated (see {work.relative_to(ROOT)}/oracle-only.txt)")
    baseline = {r[0]: r for r in read_tsv(work / "baseline.tsv")}
    for r in sorted(rows.values()):
        if r[0] in baseline and worse(baseline[r[0]], r):
            print(f"  worse: {r[0]}: {r[1]} {r[2]} (baseline: {baseline[r[0]][1]}, {baseline[r[0]][3]} same)")


if __name__ == "__main__":
    if len(sys.argv) not in (2, 3) or sys.argv[1] not in [*MODULES, "all"]:
        sys.exit(__doc__)
    for m in MODULES if sys.argv[1] == "all" else [sys.argv[1]]:
        compile_module(m, sys.argv[2] if len(sys.argv) == 3 else "")
