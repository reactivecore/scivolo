"""Writes libs/jdk-stubs/JdkConstants.scala and JdkClassConstants.scala: the public constants
(`static final` fields with a `ConstantValue`) of the JDK classes javalib defines and of the
`java.lang` classes it lacks, as `javap -constants` of the JDK on the path lists them; that JDK
must be JDK 21. Classes the other files of libs/jdk-stubs declare are left out; their missing
constants are printed."""
import re
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JAVALIB = ROOT / "libs/javalib-tasty-0.5.12.jar"
STUBS = ROOT / "libs/jdk-stubs"
OUT = STUBS / "JdkConstants.scala"
OUT_CLASSES = STUBS / "JdkClassConstants.scala"
JDK = "21"
HEADER = f"""\
// Generated by `python3 scripts/jdk_constants.py` from JDK {JDK}: the JDK's constants of classes
// javalib defines and the other files here do not declare, typed as their constants.
import scala.annotation.static
"""
HEADER_CLASSES = f"""\
// Generated by `python3 scripts/jdk_constants.py` from JDK {JDK}: the JDK's constants of `java.lang`
// classes javalib does not define, typed as their constants, as JdkClasses.scala's classes.
import scala.annotation.static
"""
CLASS = re.compile(r"^(?:public |protected )?(?:abstract |final |sealed |non-sealed )*(class|interface) ([\w.$]+)")
FIELD = re.compile(r"^  public static final (byte|short|int|long|float|double|char|boolean|java\.lang\.String) (\w+) = (.*);$")
NUMBER = {"byte": "scala.Byte", "short": "scala.Short"}
SPECIAL = {"NaN": "0.0{s} / 0.0{s}", "Infinity": "1.0{s} / 0.0{s}", "-Infinity": "-1.0{s} / 0.0{s}"}


def javalib_classes():
    names = zipfile.ZipFile(JAVALIB).namelist()
    return sorted(n[:-6].replace("/", ".") for n in names
                  if n.startswith(("java/", "javax/")) and n.endswith(".tasty"))


def lang_classes():
    """java.base's top-level classes of `java.lang`, javalib's or not."""
    modules = Path(shutil.which("javap")).resolve().parent.parent / "lib/modules"
    out = subprocess.run(["jimage", "list", str(modules)], capture_output=True, text=True).stdout
    module, names = "", []
    for line in out.splitlines():
        if line.startswith("Module: "):
            module = line.split()[1]
        elif module == "java.base" and (m := re.fullmatch(r"\s*(java/lang/\w+)\.class", line)):
            names.append(m.group(1).replace("/", "."))
    return names


def declared():
    """The fully qualified objects the other stub files declare, with their member names."""
    objects = {}
    for f in sorted(STUBS.glob("*.scala")):
        if f in (OUT, OUT_CLASSES):
            continue
        package, current = "", None
        for line in f.read_text().splitlines():
            if m := re.match(r"^package ([\w.]+) \{", line):
                package = m.group(1)
            elif m := re.match(r"^  (?:private\[\w+\] )?object (\w+)", line):
                current = objects.setdefault(f"{package}.{m.group(1)}", set())
                current.update(re.findall(r"(?:val|def) (\w+)", line))
            elif current is not None and line.startswith("    "):
                current.update(re.findall(r"(?:val|def) (\w+)", line))
            elif not line.startswith("    "):
                current = None
    return objects


def literal(kind, value):
    if kind in ("float", "double"):
        suffix = value[-1]
        number = value[:-1]
        if number in SPECIAL:
            return SPECIAL[number].format(s=suffix)
        return number + suffix
    if kind == "long":
        return value[:-1] + "L"
    return value


def constants(classes):
    """Per class its kind (`class` or `trait`) and its constants as Scala declarations."""
    out = subprocess.run(["javap", "-constants", "-public", *classes], capture_output=True, text=True).stdout
    result, current = {}, None
    for line in out.splitlines():
        if m := CLASS.match(line):
            name = re.sub(r"<.*", "", m.group(2))
            current = result.setdefault(name, ("trait" if m.group(1) == "interface" else "class", []))
        elif current is not None and (m := FIELD.match(line)):
            kind, name, value = m.groups()
            ascribed = f": {NUMBER[kind]}" if kind in NUMBER else ""
            current[1].append((name, f"@static final val {name}{ascribed} = {literal(kind, value)}"))
    return result


def main():
    version = subprocess.run(["javap", "-version"], capture_output=True, text=True).stdout.strip()
    if version.split(".")[0] != JDK:
        sys.exit(f"javap of JDK {JDK} expected, found {version}")
    javalib = set(javalib_classes())
    found = constants(sorted(javalib | set(lang_classes())))
    others = declared()
    packages = {OUT: {}, OUT_CLASSES: {}}
    for full, (kind, fields) in sorted(found.items()):
        if not fields or "$" in full:
            continue
        if full in others:
            for name, d in fields:
                if name not in others[full]:
                    print(f"undeclared in {full}: {d}")
            continue
        package, _, simple = full.rpartition(".")
        out = packages[OUT if full in javalib else OUT_CLASSES]
        out.setdefault(package, []).append((simple, kind, fields))
    for path, header in ((OUT, HEADER), (OUT_CLASSES, HEADER_CLASSES)):
        text = [header]
        for package, objects in sorted(packages[path].items()):
            text.append(f"\npackage {package} {{\n")
            for simple, kind, fields in objects:
                text.append(f"  {kind} {simple}\n  object {simple} {{\n")
                text.extend(f"    {d}\n" for _, d in fields)
                text.append("  }\n")
            text.append("}\n")
        path.write_text("".join(text))


main()
