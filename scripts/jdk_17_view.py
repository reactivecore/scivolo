"""Writes crates/lower/src/symbols/jdk_17_missing.rs: the public methods of javalib's classes that
JDK 17 or 21 has, public, by class and name, whose name JDK 17's class lacks
(`scripts/JdkMembers.java`, run by `java` of JDK 21 on the path and scala-cli's JDK 17), from the
NIR of ref/libs's javalib. Fails if javalib has an overload JDK 17 lacks of an interface method
name JDK 17 has."""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JAVALIB = ROOT / "ref/libs/javalib_native0.5_3-0.5.12.jar"
OUT = ROOT / "crates/lower/src/symbols/jdk_17_missing.rs"
DUMP = ROOT / "target/release/scivolo-nir-dump"
METHODS = ROOT / "tmp/jdk-17-view/methods.tsv"
CHECKER = ROOT / "scripts/JdkMembers.java"
DEF = re.compile(r"^(?:[a-z]+ )*def @((?:java|javax)\.[\w.$]+)::(\w+)\(([^)]*)\)")


def seen(cmd):
    out = subprocess.run([*cmd, str(METHODS)], capture_output=True, text=True, check=True).stdout
    return {tuple(f[:3]): (f[3], f[4]) for f in (line.split("\t") for line in out.splitlines())}


def main():
    version = subprocess.run(["java", "-version"], capture_output=True, text=True).stderr
    if 'version "21' not in version:
        sys.exit(f"java of JDK 21 expected, found {version.splitlines()[0]}")
    nir = subprocess.run([str(DUMP), "--dump", str(JAVALIB)], capture_output=True, text=True, check=True).stdout
    methods = sorted({m.groups() for line in nir.splitlines() if (m := DEF.match(line))})
    METHODS.parent.mkdir(parents=True, exist_ok=True)
    METHODS.write_text("".join("\t".join(m) + "\n" for m in methods))
    jdk21 = seen(["java", str(CHECKER)])
    jdk17 = seen(["scala-cli", "run", "--server=false", "--quiet", "--jvm", "17", str(CHECKER), "--"])
    overloads = sorted(m for m, (found, kind) in jdk17.items() if found == "name" and kind == "interface")
    if overloads:
        sys.exit(f"overloads JDK 17 lacks of interface methods it has: {overloads}")
    public = jdk17.keys() | jdk21.keys()
    rows = sorted({m[:2] for m in methods if m in public and jdk17.get(m, ("none",))[0] == "none"})
    lines = [f'    ("{c}", "{n}"),' for c, n in rows]
    OUT.write_text(f"""\
// Generated by `python3 scripts/jdk_17_view.py`.
//! The public methods of javalib's JDK classes whose names JDK 17 lacks: each class and method
//! name, sorted.

pub static MISSING: [(&str, &str); {len(rows)}] = [
{chr(10).join(lines)}
];
""")
    print(f"{len(rows)} methods in {OUT.relative_to(ROOT)}")


main()
