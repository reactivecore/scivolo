//> using scala 3.9.0
@main def unitarrays(): Unit =
  val a = new Array[Unit](2)
  println(a.toList)
  println(a(1))
  a(0) = ()
  println(a.toList)
  println(a.clone().toList)
  val b = new Array[Unit](3)
  System.arraycopy(a, 0, b, 1, 2)
  println(b.toList)
  println(Array.ofDim[Unit](2).toList)
  println(Array.fill(2)(()).toList)
  println(Array[Unit]((), ()).toList)
  println(a.map(x => x).toList)
  println(a.mkString(","))
  println(Array.copyOf(a, 3).toList)
  println(a.toSeq)
  println(a.iterator.toList)
  println(a.sameElements(new Array[Unit](2)))
